from __future__ import annotations

from datetime import datetime
from enum import Enum
from uuid import UUID, uuid4

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    Enum as SQLAlchemyEnum,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    Uuid,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base, UTCDateTime, utc_now


class DocumentStatus(str, Enum):
    QUEUED = "queued"
    PROCESSING = "processing"
    COMPLETED = "completed"
    FAILED = "failed"


class JobStatus(str, Enum):
    QUEUED = "queued"
    RUNNING = "running"
    SUCCEEDED = "succeeded"
    FAILED = "failed"


class JobKind(str, Enum):
    PROCESS_DOCUMENT = "process_document"


def enum_column(enum_class: type[Enum], name: str) -> SQLAlchemyEnum:
    """Persist enum values, with portable database CHECK constraints."""
    return SQLAlchemyEnum(
        enum_class,
        name=name,
        native_enum=False,
        create_constraint=True,
        validate_strings=True,
        values_callable=lambda members: [member.value for member in members],
    )


class Document(Base):
    __tablename__ = "documents"

    __table_args__ = (
        CheckConstraint("size_bytes > 0", name="positive_size"),
        CheckConstraint(
            "progress_percent >= 0 AND progress_percent <= 100",
            name="valid_progress",
        ),
        CheckConstraint(
            "processed_units >= 0",
            name="nonnegative_processed_units",
        ),
        CheckConstraint(
            "total_units IS NULL OR total_units >= 0",
            name="nonnegative_total_units",
        ),
        CheckConstraint(
            "total_units IS NULL OR processed_units <= total_units",
            name="processed_units_within_total",
        ),
        Index("ix_documents_created_at_id", "created_at", "id"),
        Index("ix_documents_status_created_at", "status", "created_at"),
    )

    id: Mapped[UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid4,
    )

    # This is a sanitized display name, never a filesystem path.
    original_filename: Mapped[str] = mapped_column(String(255), nullable=False)

    # Generated by the storage service, never supplied by an uploader.
    storage_key: Mapped[str] = mapped_column(
        String(512),
        nullable=False,
        unique=True,
    )
    storage_backend: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="local",
        server_default="local",
    )

    extension: Mapped[str] = mapped_column(String(10), nullable=False)
    media_type: Mapped[str] = mapped_column(String(100), nullable=False)
    size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)

    # Indexed but deliberately not unique: repeated uploads remain traceable.
    sha256: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        index=True,
    )

    status: Mapped[DocumentStatus] = mapped_column(
        enum_column(DocumentStatus, "document_status"),
        nullable=False,
        default=DocumentStatus.QUEUED,
        server_default=DocumentStatus.QUEUED.value,
    )
    processing_stage: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        default="queued",
        server_default="queued",
    )
    progress_percent: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default="0",
    )

    # Units will represent pages, image frames, or spreadsheet sheets.
    # Unknown totals remain NULL until a processor determines them.
    total_units: Mapped[int | None] = mapped_column(Integer, nullable=True)
    processed_units: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default="0",
    )

    # Store safe summaries only; never credentials or complete tracebacks.
    error_code: Mapped[str | None] = mapped_column(String(100), nullable=True)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime(),
        nullable=False,
        default=utc_now,
    )
    updated_at: Mapped[datetime] = mapped_column(
        UTCDateTime(),
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )
    processing_started_at: Mapped[datetime | None] = mapped_column(
        UTCDateTime(),
        nullable=True,
    )
    processing_finished_at: Mapped[datetime | None] = mapped_column(
        UTCDateTime(),
        nullable=True,
    )

    jobs: Mapped[list[ProcessingJob]] = relationship(
        back_populates="document",
        cascade="all, delete-orphan",
        passive_deletes=True,
        order_by="ProcessingJob.created_at",
    )


class ProcessingJob(Base):
    __tablename__ = "processing_jobs"

    __table_args__ = (
        CheckConstraint("attempt_count >= 0", name="nonnegative_attempt_count"),
        CheckConstraint("max_attempts >= 1", name="positive_max_attempts"),
        CheckConstraint(
            "attempt_count <= max_attempts",
            name="attempt_count_within_limit",
        ),
        CheckConstraint(
            "status != 'running' OR "
            "(locked_by IS NOT NULL AND lease_token IS NOT NULL "
            "AND lease_expires_at IS NOT NULL)",
            name="running_job_has_lease",
        ),
        Index(
            "ix_processing_jobs_claim",
            "status",
            "available_at",
            "created_at",
        ),
        Index(
            "ix_processing_jobs_expired_lease",
            "status",
            "lease_expires_at",
        ),
        # Both supported databases enforce one active job per document.
        Index(
            "uq_processing_jobs_active_document",
            "document_id",
            unique=True,
            sqlite_where=text("status IN ('queued', 'running')"),
            postgresql_where=text("status IN ('queued', 'running')"),
        ),
    )

    id: Mapped[UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid4,
    )
    document_id: Mapped[UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("documents.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    kind: Mapped[JobKind] = mapped_column(
        enum_column(JobKind, "processing_job_kind"),
        nullable=False,
        default=JobKind.PROCESS_DOCUMENT,
        server_default=JobKind.PROCESS_DOCUMENT.value,
    )
    status: Mapped[JobStatus] = mapped_column(
        enum_column(JobStatus, "processing_job_status"),
        nullable=False,
        default=JobStatus.QUEUED,
        server_default=JobStatus.QUEUED.value,
    )

    attempt_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default="0",
    )

    # The upload service must copy this value from application settings.
    # Each job retains its own retry limit if settings later change.
    max_attempts: Mapped[int] = mapped_column(Integer, nullable=False)

    available_at: Mapped[datetime] = mapped_column(
        UTCDateTime(),
        nullable=False,
        default=utc_now,
    )

    locked_by: Mapped[str | None] = mapped_column(String(100), nullable=True)

    # Each claim receives a fresh token. Worker updates will check it to
    # prevent an expired worker from overwriting a newer worker's results.
    lease_token: Mapped[UUID | None] = mapped_column(
        Uuid(as_uuid=True),
        nullable=True,
    )
    lease_expires_at: Mapped[datetime | None] = mapped_column(
        UTCDateTime(),
        nullable=True,
    )
    heartbeat_at: Mapped[datetime | None] = mapped_column(
        UTCDateTime(),
        nullable=True,
    )

    last_error_code: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
    )
    last_error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime(),
        nullable=False,
        default=utc_now,
    )
    updated_at: Mapped[datetime] = mapped_column(
        UTCDateTime(),
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )
    started_at: Mapped[datetime | None] = mapped_column(
        UTCDateTime(),
        nullable=True,
    )
    finished_at: Mapped[datetime | None] = mapped_column(
        UTCDateTime(),
        nullable=True,
    )

    document: Mapped[Document] = relationship(back_populates="jobs")
